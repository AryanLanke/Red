"""Write installer/requirements-lock.txt: every package the installed Red needs, pinned with the SHA-256 of
its Windows wheel, including the packages the pinned ones pull in.

    python installer\\lock.py

pip resolves requirements.txt (which includes the voice and UI files) for Python 3.11 on Windows, wheels only,
and reports exactly which file it would use for each package. This script turns that report into a lock file.
`build.ps1` then downloads and installs with `--require-hashes`, so a wheel that changed on PyPI is refused.
Run it again when requirements*.txt changes, and read the diff.
"""

from __future__ import annotations

import json
import subprocess
import sys
import tempfile
from pathlib import Path

HERE = Path(__file__).resolve().parent
ROOT = HERE.parent


def main() -> int:
    with tempfile.TemporaryDirectory() as tmp:
        report = Path(tmp) / "report.json"
        cmd = [sys.executable, "-m", "pip", "install", "--dry-run", "--ignore-installed", "--only-binary=:all:",
               "--python-version", "3.11", "--platform", "win_amd64", "--target", str(Path(tmp) / "target"),
               "--report", str(report), "-r", str(ROOT / "requirements.txt"), "-q"]
        done = subprocess.run(cmd, capture_output=True, text=True)
        if done.returncode != 0:
            print(done.stdout, done.stderr, file=sys.stderr)
            return done.returncode
        data = json.loads(report.read_text(encoding="utf-8"))
    lines = ["# Generated by installer/lock.py from requirements.txt: Python 3.11, Windows x64, wheels only.",
             "# Do not edit by hand; run `python installer\\lock.py` and read the diff."]
    for item in sorted(data["install"], key=lambda i: i["metadata"]["name"].lower()):
        meta, info = item["metadata"], item["download_info"]
        sha = info.get("archive_info", {}).get("hashes", {}).get("sha256")
        if not sha:
            print(f"no sha256 for {meta['name']}", file=sys.stderr)
            return 1
        file = info["url"].rsplit("/", 1)[-1]
        lines.append(f"{meta['name']}=={meta['version']} --hash=sha256:{sha}   # {file}")
    (HERE / "requirements-lock.txt").write_text("\n".join(lines) + "\n", encoding="utf-8")
    print(f"{len(lines) - 2} packages pinned in installer/requirements-lock.txt")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
